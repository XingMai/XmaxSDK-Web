import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { createHash } from 'node:crypto';

// 固定依赖中的模型转换为纯 JS 资源；Vite、ESM、CJS 均不需要额外 loader 或 CDN。
const require = createRequire(import.meta.url);
const root = dirname(require.resolve('framegen'));
const metadata = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const weights = await readFile(join(root, 'weights/rt_v7s.bin'));
const manifest = JSON.parse(await readFile(join(root, 'weights/rt_v7s.json'), 'utf8'));
const hash = createHash('sha256').update(weights).digest('hex');
const output = `// Generated by scripts/embed-framegen.mjs. Do not edit.\n` +
  `// framegen ${metadata.version}, rt_v7s.bin SHA-256: ${hash}\n` +
  `export const weightsBase64 = ${JSON.stringify(weights.toString('base64'))};\n` +
  `export const weightsManifest = ${JSON.stringify(manifest)};\n`;
await writeFile(new URL('../src/Foundation/Media/Video/FramegenWeights.generated.ts', import.meta.url), output);
// 运行时源码被打包到 SDK，随产物保留原始许可说明。
const license = await readFile(join(root, 'LICENSE'), 'utf8');
await writeFile(new URL('../THIRD_PARTY_NOTICES.md', import.meta.url),
  `# Framegen ${metadata.version}\n\nhttps://github.com/MONZikWasTaken/Framegen\n\n${license}\n\n` +
  `Model weights: non-commercial research and personal use only.\n` +
  `See https://github.com/MONZikWasTaken/Framegen/blob/main/WEIGHTS_LICENSE.md.\n`);
console.log(`Embedded framegen ${metadata.version}: ${weights.length} bytes (${hash})`);
